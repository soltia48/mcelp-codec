fn block(v: &[u16; 80]) -> [i16; 80] {
    let mut a = [0i16; 80];
    for (i, &x) in v.iter().enumerate() {
        a[i] = x as i16;
    }
    a
}

#[test]
fn tilt_compensation() {
    let input = block(&TILT_IN);
    let mut out = [0i16; 80];
    postfilter::compensate_tilt(0x0196, TILT_PREV[0] as i16, &input, &mut out);
    assert_eq!(
        out.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        TILT_OUT.to_vec()
    );
}

#[test]
fn automatic_gain_control() {
    let speech = block(&AGC_SPEECH);
    let mut b = block(&AGC_IN);
    let mut gain = 0x5547u16 as i16;
    postfilter::agc(&speech, &mut b, &mut gain);
    assert_eq!(
        b.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        AGC_OUT.to_vec(),
        "block"
    );
    assert_eq!(gain as u16, 0x553a, "gain state");
}
