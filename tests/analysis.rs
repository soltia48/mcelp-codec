#[test]
fn spectrum_magnitude_and_voicing() {
    use mcelp::analysis;
    let mut block = [0i16; 160];
    for (i, &v) in INPUT.iter().enumerate() {
        block[i] = v as i16;
    }
    let mut an = Analysis::default();
    let (w, headroom) = an.window(&block);

    // The voicing measure is taken before pre-emphasis.  The reference leaves
    // the window energy (93) and the peak correlation (33) in its scratch, and
    // returns their ratio.
    assert_eq!(analysis::voicing(&w), 11627, "voicing");

    let mut w = w;
    an.preemphasise(&mut w, headroom);
    let mut s = analysis::deinterleave(&w);
    analysis::fft(&mut s);
    analysis::unpack_real(&mut s, analysis::Direction::Forward);
    let mag = analysis::magnitude(&s);
    assert_eq!(
        mag.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        MAGNITUDE.to_vec()
    );
}
