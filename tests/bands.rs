#[test]
fn per_band_excess() {
    let (mut l, mut a, mut b) = ([0i64; 20], [0i64; 20], [0i64; 20]);
    l.copy_from_slice(&LEVELS);
    a.copy_from_slice(&T1);
    b.copy_from_slice(&T2);
    assert_eq!(
        bands::excess(&l, &a).to_vec(),
        E1.to_vec(),
        "first reference"
    );
    assert_eq!(
        bands::excess(&l, &b).to_vec(),
        E2.to_vec(),
        "second reference"
    );
}

