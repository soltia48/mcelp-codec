use mcelp::gain::{self, GainState};

/// The innovation of speech.mcelp frame 40, first subframe, as the reference had it
/// when the gains were decoded (i.e. after pitch sharpening).
const CODE: [u16; 80] = [
    0x0000, 0x0000, 0x2000, 0x0000, 0x0000, 0x0000, 0x0000, 0x2000, 0x0000, 0x0000, 0x0000, 0x0000,
    0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0xe000, 0x0000, 0x0000, 0x0000,
    0x0000, 0x0000, 0x0000, 0xe000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0002, 0x1ffa,
    0x000f, 0xffe0, 0x0037, 0xffae, 0x206b, 0xff84, 0x007d, 0x05f7, 0x004a, 0xffe6, 0xffe6, 0x004a,
    0x05f7, 0x007d, 0xff84, 0x006b, 0xffad, 0xe03d, 0xdfd1, 0x002f, 0xffc3, 0x0055, 0xff8f, 0x0089,
    0xff69, 0xfa30, 0xff83, 0x0054, 0xdfe2, 0xffe2, 0x0054, 0xff84, 0xfa2a, 0xff78, 0x006a, 0xffc6,
    0x0002, 0x0033, 0xffa6, 0x206c, 0x05ff, 0x0048, 0xffe1, 0xfff2,
];

#[test]
fn gain_decoding() {
    let mut code = [0i16; 80];
    for (i, &v) in CODE.iter().enumerate() {
        code[i] = v as i16;
    }
    let mut st = GainState {
        energy: [-1914, -1995, -1914, -1246],
        ..GainState::default()
    };
    let g = gain::decode(&mut st, 1, &code);
    assert_eq!(g.pitch as u16, 0x1bf8, "pitch gain");
    assert_eq!(g.code as u16, 0x0017, "code gain");
    assert_eq!(st.energy[0] as u16, 0xe8f8, "energy memory");
}
