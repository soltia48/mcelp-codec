#[test]
fn long_filter_and_mix() {
    let mut res = [0i16; ltp::WINDOW];
    for (i, &x) in RESIDUAL.iter().enumerate() {
        res[i] = x as i16;
    }

    // The 16-tap refinement of the delayed signal, at the phase the search chose.
    let mut refined = [0i16; 80];
    let stats = ltp::refine(&res, 0x29, 3, &mut refined);
    assert_eq!(
        refined.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        REFINED.to_vec(),
        "refined"
    );
    assert_eq!(stats.correlation as u16, 0x4209, "refined correlation");
    assert_eq!(stats.energy as u16, 0x4e7b, "refined energy");
    assert_eq!(stats.corr_exp, 5, "refined correlation exponent");
    assert_eq!(stats.energy_exp, 4, "refined energy exponent");

    // Mixing the winning delayed signal back into the residual.
    let mut residual = [0i16; 80];
    for (i, &x) in MIX_RESIDUAL.iter().enumerate() {
        residual[i] = x as i16;
    }
    let delayed: Vec<i16> = MIX_DELAYED.iter().map(|&v| v as i16).collect();
    let mut out = [0i16; 80];
    ltp::mix(0x6782, &residual, &delayed, &mut out);
    assert_eq!(
        out.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        MIX_OUT.to_vec(),
        "mix"
    );
}
