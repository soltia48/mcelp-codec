#[test]
fn pitch_postfilter_search() {
    let mut res = [0i16; ltp::WINDOW];
    for (i, &x) in RESIDUAL.iter().enumerate() {
        res[i] = x as i16;
    }
    let s = ltp::search(&res, 0x29).expect("postfilter enabled");
    assert_eq!(s.phase, 3, "phase");
    assert_eq!(s.correlation as u16, 0x1f75, "correlation mantissa");
    assert_eq!(s.energy as u16, 0x4280, "energy mantissa");
    assert_eq!(s.lag, 0x29, "lag");
    assert_eq!(s.direction, 1, "direction");
    assert_eq!(s.corr_exp, 4, "correlation exponent");
    assert_eq!(s.energy_exp, 4, "energy exponent");
}
