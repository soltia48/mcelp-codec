fn lpc(v: &[u16; 11]) -> [i16; 11] {
    let mut a = [0i16; 11];
    for (i, &x) in v.iter().enumerate() {
        a[i] = x as i16;
    }
    a
}

#[test]
fn short_term_postfilter() {
    let a1 = lpc(&A1);
    let a2 = lpc(&A2);
    let probe = postfilter::probe_response(&a1, &a2);
    assert_eq!(
        probe.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        PROBE.to_vec(),
        "probe"
    );
    assert_eq!(postfilter::spectral_tilt(&probe), 0x0196, "tilt");

    let mut block = [0i16; 80];
    for (i, &v) in BLOCK_IN.iter().enumerate() {
        block[i] = v as i16;
    }
    postfilter::normalise_gain(&probe, &mut block);
    assert_eq!(
        block.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        BLOCK_OUT.to_vec(),
        "gain"
    );
}
