#[test]
fn input_highpass() {
    let mut block: Vec<i16> = IN_BLOCK.iter().map(|&v| v as i16).collect();
    let mut hp = Highpass::default();
    hp.run(&mut block);
    assert_eq!(
        block.iter().map(|&v| v as u16).collect::<Vec<_>>(),
        OUT_BLOCK.to_vec()
    );
}

#[test]
fn mulaw_expansion() {
    // The expansion table is the codec's own, not the textbook G.711 one.
    assert_eq!(preprocess::ulaw_to_linear(0xff), 0);
    assert_eq!(preprocess::ulaw_to_linear(0x7f), 0);
}
